GLYPH_W, GLYPH_H = 5, 7


def text_width(text, scale, spacing=1):
    n = len(text)
    if n == 0:
        return 0
    return (n * GLYPH_W + (n - 1) * spacing) * scale


def draw_text(px, ox, oy, text, scale, color, spacing=1):
    """px is a dict-like object supporting px[(x, y)] = (r, g, b)."""
    x = ox
    for ch in text.upper():
        glyph = FONT.get(ch, FONT[" "])
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit == "1":
                    for dy in range(scale):
                        for dx in range(scale):
                            px[(x + gx * scale + dx, oy + gy * scale + dy)] = color
        x += (GLYPH_W + spacing) * scale
    return x
